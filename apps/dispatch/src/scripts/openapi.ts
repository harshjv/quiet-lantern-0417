import { randomBytes } from 'node:crypto'
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import type { Command } from 'commander'

import { createApp } from '../app.ts'
import { AuthService } from '../auth/auth.ts'
import { createMetadataFetch } from '../auth/metadata-fetch.ts'
import { openDb } from '../db/client.ts'
import { createGitHub } from '../github/service.ts'
import { Keyring } from '../secrets/keyring.ts'
import { createStationServer } from '../station/server.ts'

export const cliDocumentPath = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../../../../packages/cli/src/openapi.gen.ts',
)

const origin = 'http://127.0.0.1'

export const openApiDocument = async () => {
  const dir = mkdtempSync(join(tmpdir(), 'dispatch-openapi-'))
  const db = openDb(join(dir, 'dispatch.sqlite'))
  const masterKey = randomBytes(32)
  const keyring = new Keyring(db, masterKey)
  const auth = new AuthService(db, masterKey, origin, createMetadataFetch(null))
  const github = createGitHub({
    db,
    keyring,
    auth,
  })
  const version = '0.0.0'
  const stations = createStationServer({
    db,
    keyring,
    blobDir: dir,
    version,
    github,
    log: () => {},
  })
  try {
    const app = createApp({
      db,
      keyring,
      auth,
      version,
      stations,
      blobDir: dir,
      github,
    })
    const response = await app.handle(new Request(`${origin}/openapi/json`))
    if (!response.ok) throw new Error(`GET /openapi/json answered ${response.status}`)
    const { paths, components, tags } = (await response.json()) as Record<string, unknown>
    return {
      tags,
      paths,
      components,
    }
  } finally {
    await stations.close()
    rmSync(dir, {
      recursive: true,
      force: true,
    })
  }
}

export const openapiCommand = (program: Command) =>
  program
    .command('openapi')
    .description(`Write the OpenAPI document sly embeds to ${cliDocumentPath}`)
    .action(async () => {
      const document = JSON.stringify(await openApiDocument(), null, 2)
      writeFileSync(
        cliDocumentPath,
        [
          '// Code generated by apps/dispatch/src/scripts/openapi.ts. DO NOT EDIT.',
          "import type { OpenApiDocument } from '@stationly/mcp'",
          '',
          `export const openApiDocument = ${document} as OpenApiDocument`,
          '',
        ].join('\n'),
      )
    })
