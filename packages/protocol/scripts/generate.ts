import { execFileSync } from 'node:child_process'
import { mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { isDeepStrictEqual } from 'node:util'
import { capabilities, Envelope, closeCodes, limits, messages, protocolVersion, stationConnectPath, subprotocol } from '../src/messages.ts'
import { errorCatalog, handshakeInvalidMessageClose, warningCatalog } from '../src/errors.ts'
import { releaseRoots } from '../src/release.ts'

type JsonSchema = { [key: string]: unknown }

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const schemaDir = join(packageRoot, 'schema')
const goModuleRoot = resolve(packageRoot, '../../go')
const goPackageDir = join(goModuleRoot, 'internal/protocol')
const schemaId = 'https://stationly.harshjv.com/schema/protocol/v1/protocol.json'
const generatedHeader = '// Code generated by packages/protocol/scripts/generate.ts. DO NOT EDIT.'

const isSchema = (value: unknown): value is JsonSchema => typeof value === 'object' && value !== null && !Array.isArray(value)

const mapSchema = (node: unknown, visit: (schema: JsonSchema) => JsonSchema): unknown => {
  if (Array.isArray(node)) return node.map(item => mapSchema(item, visit))
  if (!isSchema(node)) return node
  const mapped = Object.fromEntries(Object.entries(node).map(([key, value]) => [key, key === 'enum' || key === 'const' ? value : mapSchema(value, visit)]))
  return visit(mapped)
}

const primitiveTypes = new Set(['string', 'integer', 'number', 'boolean'])

const isStringEnum = (schema: JsonSchema | undefined) => schema?.type === 'string' && Array.isArray(schema.enum)

const normalize = (schema: JsonSchema): JsonSchema => {
  const { patternProperties, anyOf, ...rest } = schema
  if (isSchema(patternProperties) && Object.keys(patternProperties).length === 1 && '^(.*)$' in patternProperties) {
    return normalize({ ...rest, ...(anyOf ? { anyOf } : {}), additionalProperties: patternProperties['^(.*)$'] })
  }
  if (Array.isArray(anyOf) && anyOf.every(member => isSchema(member) && typeof member.const === 'string')) {
    return { ...rest, type: 'string', enum: anyOf.map(member => (member as JsonSchema).const) }
  }
  if (typeof schema.const === 'number' && Number.isInteger(schema.const)) return { ...schema, type: 'integer' }
  return schema
}

const hoistNamed = (roots: JsonSchema[]) => {
  const defs: Record<string, JsonSchema> = {}
  const hoist = (schema: JsonSchema, isDefinition: boolean): unknown => {
    const body = Object.fromEntries(
      Object.entries(schema).map(([key, value]) => [key, key === 'enum' || key === 'const' ? value : hoistValue(value)])
    )
    if (isDefinition || typeof schema.title !== 'string') return body
    register(schema.title, body)
    return { $ref: `#/$defs/${schema.title}` }
  }
  const hoistValue = (value: unknown): unknown =>
    Array.isArray(value) ? value.map(hoistValue) : isSchema(value) ? hoist(value, false) : value
  const register = (title: string, body: JsonSchema) => {
    const existing = defs[title]
    if (existing && !isDeepStrictEqual(existing, body)) throw new Error(`two different schemas are titled ${title}`)
    defs[title] = body
  }
  for (const root of roots) {
    if (typeof root.title !== 'string') throw new Error('every root schema needs a title')
    register(root.title, hoist(root, true) as JsonSchema)
  }
  return defs
}

const refName = (schema: JsonSchema) => (typeof schema.$ref === 'string' ? schema.$ref.replace('#/$defs/', '') : undefined)

const nullableForGo = (defs: Record<string, JsonSchema>) => (schema: JsonSchema): JsonSchema => {
  const anyOf = schema.anyOf
  if (!Array.isArray(anyOf) || anyOf.length !== 2) return schema
  const nonNull = anyOf.filter(member => !(isSchema(member) && member.type === 'null'))
  if (nonNull.length !== 1 || !isSchema(nonNull[0])) return schema
  const member = nonNull[0]
  const named = refName(member)
  if (named && isStringEnum(defs[named])) return { ...schema, goJSONSchema: { type: `*${named}` } }
  if (isStringEnum(member)) return { ...schema, goJSONSchema: { type: '*string' } }
  if (typeof member.type === 'string' && primitiveTypes.has(member.type) && member.enum === undefined && member.const === undefined) {
    const { anyOf: _, ...rest } = schema
    return { ...rest, ...member, type: [member.type, 'null'] }
  }
  return schema
}

const bodyTitle = (body: { title?: string }) => {
  if (!body.title) throw new Error('every message body needs a title')
  return body.title
}

const toJson = (schema: unknown) => JSON.parse(JSON.stringify(schema)) as JsonSchema

const roots = [Envelope, ...Object.values(messages).map(definition => definition.body), ...releaseRoots].map(toJson).map(root => mapSchema(root, normalize) as JsonSchema)
const hoisted = hoistNamed(roots)
const defs = Object.fromEntries(
  Object.entries(hoisted)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, schema]) => [name, mapSchema(schema, nullableForGo(hoisted))])
)

const catalog = Object.fromEntries(
  Object.entries(messages).map(([type, definition]) => [
    type,
    { from: definition.from, body: bodyTitle(definition.body), capability: definition.capability, outboxed: definition.outboxed }
  ])
)

const writeJson = (path: string, value: unknown) => writeFileSync(path, `${JSON.stringify(value, null, 2)}\n`)

rmSync(schemaDir, { recursive: true, force: true })
mkdirSync(schemaDir, { recursive: true })
writeJson(join(schemaDir, 'protocol.json'), {
  $schema: 'https://json-schema.org/draft/2020-12/schema',
  $id: schemaId,
  $defs: defs
})
writeJson(join(schemaDir, 'messages.json'), catalog)
writeJson(join(schemaDir, 'errors.json'), { errors: errorCatalog, warnings: warningCatalog })

const pascal = (value: string) =>
  value
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map(part => part[0]!.toUpperCase() + part.slice(1).toLowerCase())
    .join('')

const goFile = (lines: string[]) => [generatedHeader, '', 'package protocol', '', ...lines, ''].join('\n')

const goCatalog = goFile([
  `const Subprotocol = ${JSON.stringify(subprotocol)}`,
  '',
  `const ProtocolVersion = ${protocolVersion}`,
  '',
  `const StationConnectPath = ${JSON.stringify(stationConnectPath)}`,
  '',
  `const HandshakeInvalidMessageClose = ${handshakeInvalidMessageClose}`,
  '',
  'const (',
  ...Object.entries(closeCodes).map(([name, code]) => `Close${pascal(name.replace(/([A-Z])/g, '_$1'))} = ${code}`),
  ')',
  '',
  'const (',
  ...Object.entries(limits).map(([name, value]) => `Limit${pascal(name.replace(/([A-Z])/g, '_$1'))} = ${value}`),
  ')',
  '',
  'type Capability string',
  '',
  'const (',
  ...capabilities.map(capability => `Capability${pascal(capability)} Capability = ${JSON.stringify(capability)}`),
  ')',
  '',
  'const (',
  ...Object.keys(messages).map(type => `Message${pascal(type)} = ${JSON.stringify(type)}`),
  ')',
  '',
  'var MessageBodies = map[string]func() any{',
  ...Object.entries(messages).map(([type, definition]) => `Message${pascal(type)}: func() any { return new(${bodyTitle(definition.body)}) },`),
  '}'
])

const goErrors = goFile([
  'type ErrorCode string',
  '',
  'const (',
  ...errorCatalog.map(entry => `ErrorCode${pascal(entry.code)} ErrorCode = ${JSON.stringify(entry.code)}`),
  ')',
  '',
  'type ErrorDefinition struct {',
  'HTTPStatus int',
  'Area string',
  'CloseCode int',
  '}',
  '',
  'var ErrorCatalog = map[ErrorCode]ErrorDefinition{',
  ...errorCatalog.map(
    entry => `ErrorCode${pascal(entry.code)}: {HTTPStatus: ${entry.http ?? 0}, Area: ${JSON.stringify(entry.area)}, CloseCode: ${entry.close ?? 0}},`
  ),
  '}',
  '',
  'type WarningCode string',
  '',
  'const (',
  ...warningCatalog.map(code => `WarningCode${pascal(code)} WarningCode = ${JSON.stringify(code)}`),
  ')'
])

const go = (args: string[]) => execFileSync('go', args, { cwd: goModuleRoot, stdio: 'inherit' })

writeFileSync(join(goPackageDir, 'catalog_gen.go'), goCatalog)
writeFileSync(join(goPackageDir, 'errors_gen.go'), goErrors)
go([
  'tool',
  'go-jsonschema',
  '--package',
  'protocol',
  '--tags',
  'json',
  '--output',
  relative(goModuleRoot, join(goPackageDir, 'schema_gen.go')),
  relative(goModuleRoot, join(schemaDir, 'protocol.json'))
])
execFileSync('gofmt', ['-w', goPackageDir], { stdio: 'inherit' })
